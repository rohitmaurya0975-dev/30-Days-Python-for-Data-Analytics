# A shop sold a product.
#
# Product Price = 500
# Quantity Sold = 3
# Discount = 100
#
# Calculate:
# 1. Total sales before discount
# 2. Final sales amount


product_price = 500
quantity = 3
discount = 100

total_sales = product_price * quantity
final_sales = total_sales - discount

print("Total Sales:", total_sales)
print("Final Sales:", final_sales)